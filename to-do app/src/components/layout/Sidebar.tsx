const NAV_LINKS = [
  { to: '/',         label: 'Dashboard', Icon: IconDashboard },
  { to: '/timeline', label: 'Timeline',  Icon: IconTimeline  },
  { to: '/tasks',    label: 'Tasks',     Icon: IconTasks     },
  { to: '/settings', label: 'Settings',  Icon: IconSettings  },
  { to: '/about',    label: 'About',     Icon: IconInfo      },
  { to: '/contact',  label: 'Contact',   Icon: IconContact   },
]

export default function Sidebar() {
  const { theme, setTheme } = useThemeContext()
  const isDark = theme.mode === 'dark'

  function toggleTheme() {
    const nextId = isDark
      ? theme.id.replace('dark', 'light').replace('Dark', 'Light') || 'lightPurple'
      : theme.id.replace('light', 'dark').replace('Light', 'Dark') || 'darkPurple'
    setTheme(nextId)
  }

  return (
    <aside className="sidebar">
      <div className="sidebar-logo" aria-label="My Todos">
        <img src={logoImg} alt="My Todos" className="sidebar-logo-img" />
      </div>

      <nav className="sidebar-nav" aria-label="Main navigation">
        {NAV_LINKS.map(({ to, label, Icon }) => (
          <NavLink
            key={to}
            to={to}
            end={to === '/'}
            viewTransition
            className={({ isActive }) => `sidebar-link${isActive ? ' active' : ''}`}
            aria-label={label}
          >
            <Icon />
          </NavLink>
        ))}
      </nav>

      <div className="sidebar-bottom">
        <button
          className="sidebar-theme-btn"
          onClick={toggleTheme}
          aria-label={isDark ? 'Switch to light mode' : 'Switch to dark mode'}
        >
          {isDark ? <IconSun /> : <IconMoon />}
        </button>
      </div>
    </aside>
  )
}
